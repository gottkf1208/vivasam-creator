# 기존 단일 HTML 3편(1차시)을 공용 플레이어용 데이터 파일 courses/<id>/s1.js 로 옮긴다.
import io, re, shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]  # lesson/

def block(src, start, end=None):
    i = src.index(start); j = src.index(chr(10) + '];', i)
    return src[i + len(start): j].strip() + chr(10) + ']'

def convert(html, cid, img_dir, extra):
    s = io.open(ROOT / html, encoding='utf-8').read()
    segs = block(s, 'const SEGS = ')
    steps = block(s, 'const STEPS = ')
    # 퀴즈
    if 'const OPTS = ' in s:
        opts = re.search(r"const OPTS = (\[.*?\]);", s).group(1)
    else:
        opts = None
    items = block(s, 'const QUIZ = ')
    out = ROOT / 'courses' / cid
    (out / 'img').mkdir(parents=True, exist_ok=True)
    for f in (ROOT / img_dir).glob('*.webp'):
        shutil.copy(f, out / 'img' / f.name)
    js = "window.LESSON = {\n" + extra['head'] + "\n  segs: " + segs + ",\n  steps: " + steps + ",\n  quiz: {\n" + extra['quizhead'] + ("    opts: " + opts + ",\n" if opts else "") + "    items: " + items + ",\n" + extra['ref'] + "  },\n" + extra['tail'] + "\n};\n"
    io.open(out / 's1.js', 'w', encoding='utf-8').write(js)
    print(cid, 'written', len(js))

